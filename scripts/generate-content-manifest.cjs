#!/usr/bin/env node

const fs = require('node:fs')
const path = require('node:path')
const matter = require('gray-matter')

const ROOT = path.resolve(__dirname, '..')
const OUTPUT = path.join(ROOT, 'src', 'generated', 'content-manifest.ts')

function buildManifest(locale) {
  const docsDir = path.join(ROOT, 'docs', locale)
  const manifest = {}
  for (const file of fs
    .readdirSync(docsDir)
    .filter((name) => name.endsWith('.md'))
    .sort()) {
    const fileName = file.replace(/\.md$/, '')
    const raw = fs.readFileSync(path.join(docsDir, file), 'utf8')
    manifest[fileName] = matter(raw).data
  }
  return manifest
}

const manifest = buildManifest('en')
const vietnameseManifest = buildManifest('vn')
const vietnamesePracticeOverrides = Object.fromEntries(
  Object.entries(vietnameseManifest)
    .filter(([fileName, data]) => {
      return JSON.stringify(data.quiz ?? null) !== JSON.stringify(manifest[fileName]?.quiz ?? null)
    })
    .map(([fileName, data]) => [fileName, { quiz: data.quiz }]),
)

const generated = `/* This file is generated by scripts/generate-content-manifest.cjs. */
/* Do not edit it by hand; update docs/en frontmatter and regenerate. */

export const CONTENT_MANIFEST: Record<string, Record<string, unknown>> = ${JSON.stringify(manifest, null, 2)}

export const VI_PRACTICE_OVERRIDES: Record<string, Record<string, unknown>> = ${JSON.stringify(vietnamesePracticeOverrides, null, 2)}
`

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : ''
  if (current !== generated) {
    console.error('Content manifest is stale. Run: npm run content:manifest')
    process.exitCode = 1
  } else {
    console.log(`Content manifest is current (${Object.keys(manifest).length} lessons).`)
  }
} else {
  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true })
  fs.writeFileSync(OUTPUT, generated, 'utf8')
  console.log(
    `Generated ${path.relative(ROOT, OUTPUT)} with ${Object.keys(manifest).length} lessons.`,
  )
}
