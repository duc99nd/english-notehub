#!/usr/bin/env node

const fs = require('node:fs')
const path = require('node:path')
const matter = require('gray-matter')

const ROOT = path.resolve(__dirname, '..')
const DOCS_DIR = path.join(ROOT, 'docs', 'en')
const OUTPUT = path.join(ROOT, 'src', 'generated', 'content-manifest.ts')

const manifest = {}
for (const file of fs
  .readdirSync(DOCS_DIR)
  .filter((name) => name.endsWith('.md'))
  .sort()) {
  const fileName = file.replace(/\.md$/, '')
  const raw = fs.readFileSync(path.join(DOCS_DIR, file), 'utf8')
  manifest[fileName] = matter(raw).data
}

const generated = `/* This file is generated by scripts/generate-content-manifest.cjs. */
/* Do not edit it by hand; update docs/en frontmatter and regenerate. */

export const CONTENT_MANIFEST: Record<string, Record<string, unknown>> = ${JSON.stringify(manifest, null, 2)}
`

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : ''
  if (current !== generated) {
    console.error('Content manifest is stale. Run: npm run content:manifest')
    process.exitCode = 1
  } else {
    console.log(`Content manifest is current (${Object.keys(manifest).length} lessons).`)
  }
} else {
  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true })
  fs.writeFileSync(OUTPUT, generated, 'utf8')
  console.log(
    `Generated ${path.relative(ROOT, OUTPUT)} with ${Object.keys(manifest).length} lessons.`,
  )
}
